#!/usr/bin/env node
"use strict";

/**
 * Maintains registry.json: every IDOS vesting wallet (OpenZeppelin VestingWallet clone) on Arbitrum.
 *
 * Method (see README "Methodology"): index IDOS Transfer logs, collect every address that ever
 * received IDOS, and keep those that answer owner(), start() and end(). A wallet stays in the
 * registry forever (end() is immutable), so an incremental run only needs the blocks since the
 * last run.
 *
 *   node scripts/discover.js          # incremental, from registry.scannedToBlock
 *   node scripts/discover.js --full   # rescan from the token's first transfer
 *
 * Set ARBITRUM_RPC_URL to use another RPC endpoint.
 */

const fs = require("fs");
const path = require("path");
const { ethers } = require("ethers");
const { IDOS_TOKEN, ARBITRUM_CHAIN_ID, FIRST_TRANSFER_BLOCK, IFACE, makeProvider, multicall } = require("../lib/supply");

const REGISTRY_PATH = path.join(__dirname, "..", "registry.json");
const TRANSFER_TOPIC = ethers.id("Transfer(address,address,uint256)");
const MAX_WINDOW = 10_000_000; // the public Arbitrum RPC accepts up to 10M blocks per eth_getLogs
const REORG_MARGIN = 200;

function readRegistry() {
  if (!fs.existsSync(REGISTRY_PATH)) return { contracts: [] };
  return JSON.parse(fs.readFileSync(REGISTRY_PATH, "utf8"));
}

function writeRegistry(registry) {
  const lines = registry.contracts.map(
    (c) => `    { "address": "${c.address}", "start": ${c.start}, "end": ${c.end} }`,
  );
  const text =
    `{\n  "$comment": "Generated by scripts/discover.js. Every IDOS vesting wallet ever found on Arbitrum One; do not edit by hand.",\n` +
    `  "chainId": ${ARBITRUM_CHAIN_ID},\n  "token": "${IDOS_TOKEN}",\n  "generatedAt": "${registry.generatedAt}",\n` +
    `  "scannedToBlock": ${registry.scannedToBlock},\n  "contracts": [\n${lines.join(",\n")}\n  ]\n}\n`;
  fs.writeFileSync(REGISTRY_PATH, text);
}

function topicToAddress(topic) {
  return ("0x" + topic.slice(26)).toLowerCase();
}

/** Every address that received IDOS between fromBlock and toBlock (inclusive). */
async function scanRecipients(provider, fromBlock, toBlock) {
  const recipients = new Set();
  let from = fromBlock;
  let win = MAX_WINDOW;
  let logsTotal = 0;
  const t0 = Date.now();
  while (from <= toBlock) {
    const to = Math.min(from + win - 1, toBlock);
    try {
      const logs = await provider.send("eth_getLogs", [
        { address: IDOS_TOKEN, topics: [TRANSFER_TOPIC], fromBlock: ethers.toQuantity(from), toBlock: ethers.toQuantity(to) },
      ]);
      for (const l of logs) recipients.add(topicToAddress(l.topics[2]));
      logsTotal += logs.length;
      from = to + 1;
      if (logs.length < 1000) win = Math.min(win * 4, MAX_WINDOW);
      else if (logs.length < 5000) win = Math.min(win * 2, MAX_WINDOW);
    } catch (e) {
      if (win > 1) {
        win = Math.floor(win / 2); // too many logs for one response: narrow the window
      } else {
        // A single block over the RPC's log cap: read the block's receipts instead.
        const receipts = await provider.send("eth_getBlockReceipts", [ethers.toQuantity(from)]);
        for (const rc of receipts) {
          for (const l of rc.logs) {
            if (l.address.toLowerCase() === IDOS_TOKEN.toLowerCase() && l.topics[0] === TRANSFER_TOPIC) {
              recipients.add(topicToAddress(l.topics[2]));
              logsTotal += 1;
            }
          }
        }
        from += 1;
      }
    }
    if (logsTotal && Date.now() - t0 > 15000) {
      process.stderr.write(`  scanned up to block ${from - 1}: ${logsTotal} transfers, ${recipients.size} recipients\n`);
    }
  }
  return { recipients, logsTotal };
}

const PROBE_BATCH = 500;

/**
 * aggregate3 with recursive splitting: a chunk the RPC refuses (its eth_call gas cap, response
 * size) is halved until it goes through. A single call that still fails counts as failed.
 */
async function multicallSplit(provider, calls, attempt = 0) {
  try {
    return await multicall(provider, calls);
  } catch (e) {
    if (calls.length === 1) {
      if (attempt < 2) {
        await new Promise((r) => setTimeout(r, 1500));
        return multicallSplit(provider, calls, attempt + 1);
      }
      return [{ success: false, returnData: "0x" }];
    }
    const mid = Math.ceil(calls.length / 2);
    return [...(await multicallSplit(provider, calls.slice(0, mid))), ...(await multicallSplit(provider, calls.slice(mid)))];
  }
}

/** Keeps the addresses that answer end(), start() and owner() like an OpenZeppelin VestingWallet. */
async function probeVesting(provider, addresses) {
  const ok = (r) => r.success && r.returnData.length === 66;

  // Pass 1: end() alone, one call per address.
  const withEnd = [];
  for (let i = 0; i < addresses.length; i += PROBE_BATCH) {
    const batch = addresses.slice(i, i + PROBE_BATCH);
    const res = await multicallSplit(provider, batch.map((a) => ({ target: a, allowFailure: true, callData: IFACE.encodeFunctionData("end") })));
    batch.forEach((a, j) => {
      const end = ok(res[j]) ? Number(BigInt(res[j].returnData)) : 0;
      if (end > 0) withEnd.push({ address: a, end }); // a VestingWallet always has end() > 0
    });
    if ((i / PROBE_BATCH) % 20 === 0 || i + PROBE_BATCH >= addresses.length) {
      process.stderr.write(`  probed ${Math.min(i + PROBE_BATCH, addresses.length)}/${addresses.length} recipients, ${withEnd.length} answer end()\n`);
    }
  }

  // Pass 2: start() and owner() for those.
  const found = [];
  for (let i = 0; i < withEnd.length; i += PROBE_BATCH) {
    const batch = withEnd.slice(i, i + PROBE_BATCH);
    const res = await multicallSplit(
      provider,
      batch.flatMap((c) => [
        { target: c.address, allowFailure: true, callData: IFACE.encodeFunctionData("start") },
        { target: c.address, allowFailure: true, callData: IFACE.encodeFunctionData("owner") },
      ]),
    );
    batch.forEach((c, j) => {
      if (ok(res[2 * j]) && ok(res[2 * j + 1])) {
        found.push({ address: ethers.getAddress(c.address), start: Number(BigInt(res[2 * j].returnData)), end: c.end });
      }
    });
  }
  return found;
}

async function main() {
  const full = process.argv.includes("--full");
  const provider = makeProvider();
  const registry = full ? { contracts: [] } : readRegistry();
  const known = new Map(registry.contracts.map((c) => [c.address.toLowerCase(), c]));

  const latest = await provider.getBlockNumber();
  const from = registry.scannedToBlock ? Math.max(FIRST_TRANSFER_BLOCK, registry.scannedToBlock - REORG_MARGIN) : FIRST_TRANSFER_BLOCK;
  console.log(`${full ? "Full" : "Incremental"} scan of IDOS transfers, blocks ${from} → ${latest}`);

  const { recipients, logsTotal } = await scanRecipients(provider, from, latest);
  const fresh = [...recipients].filter((a) => !known.has(a));
  console.log(`${logsTotal} transfers, ${recipients.size} recipients, ${fresh.length} not in the registry yet`);

  const found = await probeVesting(provider, fresh);
  for (const c of found) known.set(c.address.toLowerCase(), c);

  const contracts = [...known.values()].sort((a, b) => b.end - a.end || a.address.localeCompare(b.address));
  writeRegistry({ generatedAt: new Date().toISOString(), scannedToBlock: latest, contracts });

  const now = Math.floor(Date.now() / 1000);
  const stillVesting = contracts.filter((c) => c.end > now).length;
  console.log(`registry.json: ${contracts.length} vesting wallets (${found.length} new), ${stillVesting} still vesting, scanned to block ${latest}`);
  if (found.length) {
    console.log("New wallets:");
    for (const c of found) console.log(`  ${c.address} ends ${new Date(c.end * 1000).toISOString().slice(0, 10)}`);
  }
}

if (require.main === module) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}

module.exports = { scanRecipients, probeVesting, multicallSplit };
